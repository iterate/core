// env.ts — THE SECRETS WORKER'S BINDINGS, as core/alchemy/src/stack.ts declares them. Egress
// and ingress call it. It calls the pinned hosts, and one other Worker: auth, which says who signed
// an approval (./approvals-page.ts) and signs a request to iterate Cloud (./cloud-client.ts).
import type { AuthService } from "iterate/workers";
import type { ActsGate } from "./acts-gate.ts";
import type { ApprovalsIndex } from "./approvals-index.ts";
import type { SecretDurableObject } from "./secret/durable-object.ts";

// THE BINDINGS are declared on `Cloudflare.Env`, which `import { env } from "cloudflare:workers"` is
// typed by, as `wrangler types` declares them
// (https://developers.cloudflare.com/workers/runtime-apis/bindings/#importing-env-as-a-global).
// `Env` is the same type by name.
declare global {
  namespace Cloudflare {
    interface Env {
      DOMAIN: string;
      /** Absent: the stack has no iterate Cloud. */
      CLOUD_ORIGIN?: string;
      /** The at-rest key: generated by the stack, or the deploy's `ITERATE_SECRETS_AT_REST_KEY`
       *  (core/alchemy/src/stack.ts), bound as a secret. Never returned or logged. */
      SECRETS_AT_REST_KEY: string;
      /** One object per secret, named by its path (./secret/durable-object.ts). */
      SECRET: DurableObjectNamespace<SecretDurableObject>;
      /** The Worker Loader, for a secret's exchange code alone (./secret/exchange-jail.ts). */
      LOADER: WorkerLoader;
      /** The list of secrets with an approval rule or a request waiting (./approvals-index.ts). */
      APPROVALS: DurableObjectNamespace<ApprovalsIndex>;
      /** The gate for acts that are not a secret's request: one object (./acts-gate.ts). */
      ACTS: DurableObjectNamespace<ActsGate>;
      /** The `Auth` entrypoint of the auth Worker: who signed a statement (`verify`), and a
       *  statement signed by the stack's own key (`sign`), which is how a request to iterate
       *  Cloud's broker says which deployment sent it (./cloud-client.ts). */
      AUTH: Pick<AuthService, "verify" | "sign">;
    }
  }
}

export type Env = Cloudflare.Env;
