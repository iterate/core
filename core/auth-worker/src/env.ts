// env.ts — THE AUTH WORKER'S BINDINGS, as core/alchemy/src/stack.ts declares them, and its config. The boundary
// and the secrets Worker call it; it calls no other Worker.
import { platformOriginOf } from "iterate/mind-api";
import { type AuthConfig, authConfigOf } from "./config.ts";

// THE BINDINGS are declared on `Cloudflare.Env`, which the OAuth library's types default to, as
// `wrangler types` declares them. `Env` is the same type by name.
declare global {
  namespace Cloudflare {
    interface Env {
      DOMAIN: string;
      /** JSON: ./config.ts `authConfigOf`. */
      AUTH_SETTINGS: string;
      /** Generated by the stack and bound as a secret: it signs the session and sign-in cookies
       *  (./cookies.ts). Never returned or logged. */
      AUTH_SIGNING_KEY: string;
      /** A STAND-IN FOR SIGN-IN, which goes once the real path is proven (./worker.ts
       *  `prototypeIdentity`). Bound only when the deploy's environment has it. Never returned or
       *  logged. */
      ITERATE_PROTOTYPE_TOKEN?: string;
      /** JSON: ./config.ts `FirstOwnerTicket`. Bound only by a deploy run that made a ticket
       *  (./first-owner.ts); the next deploy without one removes it. */
      FIRST_OWNER_TICKET?: string;
      /** The people (./users.ts): `users` and `identities`, from ../migrations. */
      DB: D1Database;
      /** The OAuth library's store: clients, grants, tokens, consent handles. Its name is the one
       *  the library reads. */
      OAUTH_KV: KVNamespace;
      /** The iterate Cloud the stack was deployed from, when its config names one: its pages link
       *  there for a recovery and for the AI step. */
      CLOUD_ORIGIN?: string;
      /** Cloudflare Email Sending: how a mailed sign-in code leaves (./email-sign-in.ts). */
      SEND_EMAIL: SendEmail;
    }
  }
}

export type Env = Cloudflare.Env;

const configByText = new Map<string, AuthConfig>();

/** The Worker's config, parsed once per isolate. */
export function iterateConfigOf(env: Env): AuthConfig {
  const text = `${env.DOMAIN}\n${env.AUTH_SETTINGS}`;
  let config = configByText.get(text);
  if (!config) {
    config = authConfigOf(env.DOMAIN, JSON.parse(env.AUTH_SETTINGS));
    configByText.set(text, config);
  }
  return config;
}

/** The issuer's origin: the platform's hostname under the mind's domain, `https://iterate.<domain>`
 *  (iterate/mind-api), where every page and endpoint of this Worker is. Ingress sends it every
 *  request there that is not for the API, the MCP server or the secret pages. */
export const issuerOf = (env: Env) => platformOriginOf(iterateConfigOf(env).domain);
